#!/usr/bin/env python3
"""Generate the native port's resident descriptor audit from explicit data.

Function descriptor addresses are evidence, never native execution targets.
This inventory does not claim to cover dynamic syntax or generated emitters.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = (root / 'src/poplan.cpp').read_text()
records = re.findall(r'\{(0[0-7]+), Word48\("((?:[^"\\]|\\.)*)"\), Word48\((0[0-7]+)ULL\), Word48\((0[0-7]+)ULL\), Word48\((0[0-7]+)ULL\)\}', source)
assert len(records) == 0o270, len(records)
print('<!-- Generated by python3 tools/native-inventory.py; do not edit. -->')
print('# Native resident descriptor audit\n')
print('The 184 resident records are copied from explicit bootstrap data in `src/poplan.cpp`.')
print('Class, property and binding words are historical evidence. Native bootstrap retains')
print('names/class/properties, leaves every binding unbound, and never calls these addresses.')
print('Packed-name lookup and collision-chain interning are implemented; see')
print('[native-dictionary.md](native-dictionary.md). Source tokenization, aliases,')
print('syntax mutation and per-record primitive conformance remain unimplemented.\n')
print('| Record (octal) | Name | Class | Properties | Historical binding | Native primitive status |')
print('| --- | --- | --- | --- | --- | --- |')
for record, name, cls, prop, binding in records:
    name = json.loads('"' + name + '"')
    status = 'Binary numeric probe only; binding unimplemented' if name in ('+', '-', '*', '/') else 'Unimplemented'
    print(f'| `{record}` | `{name}` | `{cls}` | `{prop}` | `{binding}` | {status} |')
